// Chave única do exercício (funciona também para treinos antigos salvos sem id)
export const exKey = (e) => findExercise(e)?.id || e?.id || e?.gif;

function isLang(code) {
  return LANGS.some((l) => l.code === code);
}

function detectLang() {
  try {
    const fromUrl = new URLSearchParams(window.location.search).get('lang');
    if (isLang(fromUrl)) return fromUrl;
  } catch (e) {}
  try {
    const saved = window.localStorage.getItem(STORAGE_KEY);
    if (isLang(saved)) return saved;
  } catch (e) {}
  const nav = (navigator.languages || [navigator.language || '']).map((l) => (l || '').slice(0, 2).toLowerCase());
  const match = nav.find(isLang);
  return match || DEFAULT_LANG;
}

const LangContext = createContext(null);

export function LangProvider({ children }) {
  const [lang, setLangState] = useState(DEFAULT_LANG);

  useEffect(() => {
    const l = detectLang();
    setLangState(l);
    try {
      window.localStorage.setItem(STORAGE_KEY, l);
    } catch (e) {}
  }, []);

  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);

  const setLang = useCallback((l) => {
    if (!isLang(l)) return;
    setLangState(l);
    try {
      window.localStorage.setItem(STORAGE_KEY, l);
    } catch (e) {}
  }, []);

  return <LangContext.Provider value={{ lang, setLang }}>{children}</LangContext.Provider>;
}

export function useI18n() {
  const ctx = useContext(LangContext) || { lang: DEFAULT_LANG, setLang: () => {} };
  const { lang, setLang } = ctx;
  useCatalog(); // re-renderiza quando o catálogo termina de carregar
  const t = (key) => dict[lang][key] ?? dict[DEFAULT_LANG][key] ?? key;
  // Texto com valores: tf('useWeight', { kg: 60 }) -> "Usar 60 kg"
  const tf = (key, params = {}) => t(key).replace(/\{(\w+)\}/g, (_, k) => (params[k] ?? ''));
  const locale = LANGS.find((l) => l.code === lang).locale;

  const exName = (ex) => {
    const cat = findExercise(ex);
    if (cat) return cat.name[lang];
    return typeof ex?.name === 'object' ? ex.name[lang] : ex?.name || '';
  };
  const catName = (key) => categories[key]?.[lang] || key || '';
  const muscleName = (key) => muscles[key]?.[lang] || key || '';
  const bodyPartName = (key) => bodyParts[key]?.[lang] || key || '';
  const equipName = (key) => equipment[key]?.[lang] || key || '';
  const targetName = (key) => targets[key]?.[lang] || key || '';
  // Linha curta: "Peitoral · Barra" (catálogo novo) ou "Calistenia · Pernas" (antigo)
  const exMeta = (ex) => {
    const cat = findExercise(ex);
    if (!cat) return '';
    if (!cat.legacy) return [targetName(cat.target), equipName(cat.eq)].filter(Boolean).join(' · ');
    return catName(cat.cat) + (cat.muscle ? ` · ${muscleName(cat.muscle)}` : '');
  };

  return { lang, setLang, t, tf, locale, exName, catName, muscleName, bodyPartName, equipName, targetName, exMeta };
}
